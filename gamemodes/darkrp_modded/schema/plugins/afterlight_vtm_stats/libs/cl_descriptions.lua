function ix.vtm.descriptions.Get(kind, id, level)
	local pool = kind == "disciplines" and ix.vtm.descriptions.disciplines or ix.vtm.descriptions.stats
	local entry = pool[id] and pool[id][level]
	if (!entry) then return nil end
	return entry[1], entry[2]
end
